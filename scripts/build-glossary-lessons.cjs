// Generates lib/glossary/claude-lessons.ts: which lesson teaches each glossary term on each track, and each lesson's
// key rule for link previews. Lesson text stays server-only; this file carries only titles and takeaways.
// Run: node scripts/build-glossary-lessons.cjs   (check-glossary.cjs fails when the output is stale)
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

require.extensions[".ts"] = (module, file) => {
  const { outputText } = ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  module._compile(outputText, file);
};

const root = path.join(__dirname, "..");
const { lessonSets } = require(path.join(root, "lib/claude/lessons/index.ts"));
const { claudeGlossary } = require(path.join(root, "lib/glossary/claude.ts"));

function generate() {
  const termLessons = {};
  const previews = {};
  for (const [track, set] of Object.entries(lessonSets)) {
    previews[track] = {};
    for (const lesson of set.lessons) {
      previews[track][lesson.objective] = [lesson.title, lesson.takeaway];
      for (const term of lesson.terms) {
        const linked = [
          ...claudeGlossary.entries.filter(({ forms, lessonTerms }) => forms.includes(term) || lessonTerms?.includes(term)),
          ...claudeGlossary.patterns.filter(({ lessonTerms }) => lessonTerms?.includes(term)),
        ];
        for (const { id } of linked) {
          termLessons[id] ??= {};
          termLessons[id][track] ??= lesson.objective;
        }
      }
    }
  }
  const sorted = Object.fromEntries(Object.entries(termLessons).sort(([a], [b]) => a.localeCompare(b)));
  return `// Generated by scripts/build-glossary-lessons.cjs from the lesson files. Do not edit by hand.
import type { TrackId } from "../claude/blueprints";

/** Glossary entry id → the first lesson on each track whose terms include it. */
export const termLessons: Record<string, Partial<Record<TrackId, string>>> = ${JSON.stringify(sorted, null, 2)};

/** Lesson title and key rule by track and objective, for previews on lesson links. */
export const lessonPreviews: Record<TrackId, Record<string, readonly [title: string, takeaway: string]>> = ${JSON.stringify(previews, null, 2)};
`;
}

module.exports = { generate, output: path.join(root, "lib/glossary/claude-lessons.ts") };

if (require.main === module) {
  fs.writeFileSync(module.exports.output, generate());
  console.log(`Wrote ${path.relative(root, module.exports.output)}`);
}
