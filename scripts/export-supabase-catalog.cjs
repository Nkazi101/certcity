const { createHash } = require("node:crypto");
const fs = require("node:fs");
const ts = require("typescript");

require.extensions[".ts"] = (module, file) => {
  const code = ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  module._compile(code.outputText, file);
};

const { blueprint, tracks, trackTitle } = require("../lib/claude/blueprints.ts");
const { banks } = require("../lib/claude/practice.ts");
const { missionFollowupQuestions, missionQuestions, portfolio } = require("../lib/claude/pathway.ts");
const { missionMappings } = require("../lib/claude/missions.ts");
const { places } = require("../lib/world.ts");
const { sources } = require("../lib/claude/items.ts");

const release = 1;
const output = ["-- Initial catalog snapshot. Generated by node scripts/export-supabase-catalog.cjs."];
function sql(value) {
  return typeof value === "number" ? String(value) : "'" + value.replaceAll("'", "''") + "'";
}
function insert(table, columns, records) {
  if (records.length) output.push(
    `insert into ${table} (${columns.join(", ")}) values\n` +
    records.map((row) => "  (" + row.map(sql).join(", ") + ")").join(",\n") + ";",
  );
}
function objectiveNumbers(code) {
  const numbers = code.split(".").map(Number);
  if (numbers.length !== 2 || numbers.some((value) => !Number.isInteger(value) || value <= 0)) {
    throw new Error(`Invalid objective ${code}`);
  }
  return numbers;
}

insert("public.city_places", ["id", "district_id", "name"], places.map(({ id, district, name }) => [id, district, name]));
for (const track of tracks) {
  const { id } = track;
  const missions = portfolio.filter((mission) => mission.track === id);
  const missionIds = new Set(missions.map((mission) => mission.id));
  const placed = new Set(places.map((place) => place.id));
  const items = new Map();
  const forms = [];
  const formItems = [];

  function form(formId, kind, questions, mission = null) {
    if (!questions.length) return;
    forms.push([id, release, formId, mission?.id ?? "", kind]);
    questions.forEach((item, index) => {
      if (items.has(item.id) && items.get(item.id).objective !== item.objective) {
        throw new Error(`Objective collision for ${item.id}`);
      }
      if (!items.has(item.id)) items.set(item.id, item);
      formItems.push([id, release, formId, item.id, index + 1]);
    });
  }

  form("exam-practice", "practice", banks[id].practice);
  form("exam-followup", "followup", banks[id].followup);
  for (const mission of missions) {
    if (!placed.has(mission.place) || mission.requires?.some((prerequisite) => !missionIds.has(prerequisite))) {
      throw new Error(`Invalid place or prerequisite for ${mission.id}`);
    }
    form(mission.id + "-check", "mission_check", missionQuestions(mission), mission);
    form(mission.id + "-followup", "followup", missionFollowupQuestions(mission), mission);
  }

  const missionRows = missions.map((mission) => [id, release, mission.id, mission.place, mission.kind, mission.title, mission.brief, "prototype-v1"]);
  const prerequisiteRows = missions.flatMap((mission) => (mission.requires ?? [])
    .map((prerequisite) => [id, release, mission.id, prerequisite]));
  const objectiveRows = missions.flatMap((mission) => [
    ...new Set(missionMappings(mission).map(({ objective }) => objective)),
  ].map((objective) => [id, release, mission.id, blueprint, ...objectiveNumbers(objective), "taught"])
    .concat((mission.verify ?? []).map((objective) => [id, release, mission.id, blueprint, ...objectiveNumbers(objective), "required"])));
  const itemRows = [...items.values()].map((item) => [id, release, item.id, item.id, blueprint,
    ...objectiveNumbers(item.objective), sources[item.source][1],
    JSON.stringify({ scenario: item.scenario, prompt: item.prompt, options: item.options }),
    JSON.stringify({ correct: item.correct, explanation: item.explanation, rationales: item.rationales })]);
  const hash = createHash("sha256").update(JSON.stringify({
    track, missionRows, prerequisiteRows, objectiveRows, forms, formItems, itemRows,
  })).digest("hex");

  insert("public.certification_tracks", ["id", "credential_code", "title"], [[id, track.code, trackTitle(track)]]);
  insert("public.blueprint_versions", ["track_id", "version", "guide_url"], [[id, blueprint, track.guide]]);
  insert("public.blueprint_domains", ["track_id", "blueprint_version", "domain_no", "title", "weight_basis_points"],
    track.domains.map((domain) => [id, blueprint, domain.id, domain.title, Math.round(domain.weight * 100)]));
  insert("public.blueprint_objectives", ["track_id", "blueprint_version", "domain_no", "objective_no", "title"],
    track.domains.flatMap((domain) => domain.objectives.map((title, index) => [id, blueprint, domain.id, index + 1, title])));
  insert("public.content_releases", ["track_id", "release_no", "blueprint_version", "content_sha256"], [[id, release, blueprint, hash]]);
  insert("public.missions", ["track_id", "mission_id"], missions.map((mission) => [id, mission.id]));
  insert("public.mission_revisions", ["track_id", "release_no", "mission_id", "place_id", "kind", "title", "brief", "engine_version"], missionRows);
  insert("public.mission_prerequisites", ["track_id", "release_no", "mission_id", "prerequisite_id"], prerequisiteRows);
  insert("public.mission_objectives", ["track_id", "release_no", "mission_id", "blueprint_version", "domain_no", "objective_no", "purpose"], objectiveRows);

  // The prototype shipped these answers to browsers. An item ID is a provisional family
  // for study tracking. Independent families require separately authored and reviewed items.
  insert("certcity_private.item_families", ["track_id", "family_id", "eligibility"],
    [...items.keys()].map((itemId) => [id, itemId, "study_only"]));
  insert("certcity_private.item_revisions", [
    "track_id", "release_no", "item_id", "family_id", "blueprint_version", "domain_no", "objective_no", "source_url", "prompt", "rubric",
  ], itemRows);
  if (forms.length) output.push(
    "insert into certcity_private.assessment_forms (track_id, release_no, form_id, mission_id, kind) values\n" +
    forms.map((row) => "  (" + row.map((value, index) => index === 3 && value === "" ? "null" : sql(value)).join(", ") + ")").join(",\n") + ";",
  );
  insert("certcity_private.assessment_form_items", ["track_id", "release_no", "form_id", "item_id", "position"], formItems);
}
output.push("update public.content_releases set published_at = now() where release_no = 1;");
output.push("insert into public.current_content_releases (track_id, release_no) select track_id, release_no from public.content_releases where release_no = 1;");
process.stdout.write(output.join("\n\n") + "\n");
